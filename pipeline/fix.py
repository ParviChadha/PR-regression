#!/usr/bin/env python3
"""Repair pass (pipeline stage "Fix"): make generated programs that are wasted or half-informative useful again.

Usage:  python3 pipeline/fix.py <target> --pr N [--rounds 2] [--max-per-round 15] [--per-signature 4] [--model M] [--dry-run] [--force]
                                [--docker] [--std c++17] [--runs 3] [--timeout 10] [--compile-timeout 180] [--jobs 4]
Run generate.py and run.py first (needs data/<t>/tests/<pr>/generated.json and results.json). Needs GEMINI_API_KEY
(in .env or exported) unless every response is cached.

Which programs are repaired (from results.json):
  compile  status invalid because the program fails to compile the same way on both versions (typo, wrong header,
           missing include). One request asks for a corrected program; the intent must stay.
  detect   compile_diff that fails on OLD only: the program uses an API or type the old library rejects, so it never
           shows what the new library does with it. The model rewrites it with the detection idiom (void_t / requires)
           and `if constexpr`, so it compiles on both versions, prints whether the expression is supported, and
           exercises it when it is.
Never repaired, because they are the findings: compile_diff that fails on NEW only, or on both with a different first
error (compile_failed_on "both"), output_diff, flaky, runtime timeouts.

One request per round (all candidates together). Each repair is a NEW file (gen_NN.cpp, next free number) with
"fixes": <original>, "kind" and "round" in generated.json; the original gets "superseded_by". Originals stay on disk so
results stay coherent and the evidence is kept; later stages skip superseded entries. Repairs are compiled and run on
both versions straight away and merged into results.json; a repair that still fails is a candidate again next round
(at most --rounds). Re-running generate.py replaces gen_*.cpp and so discards repairs.
"""
import argparse
import json
import re
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT))
from pipeline.common import Target, write_text  # noqa: E402
import generate  # noqa: E402
import llm  # noqa: E402
import run  # noqa: E402

SCHEMA = {"type": "OBJECT", "properties": {"fixes": {"type": "ARRAY", "items": {
    "type": "OBJECT", "properties": {"file": {"type": "STRING"}, "code": {"type": "STRING"}},
    "required": ["file", "code"]}}}, "required": ["fixes"]}

KIND_TEXT = {
    "compile": ("COMPILE ERROR. The program fails to compile, the same way against the old and the new library. Fix the "
                "error (wrong or missing include, typo, misuse of the public API) and keep the intent: the call under test "
                "must stay. Include only headers that exist; if you are unsure a header exists, use the library's main header."),
    "detect": ("DETECTION REWRITE. The program fails to compile against the OLD library because the API or type it uses is "
               "not accepted there; it compiles against the NEW one. Rewrite it so it compiles against both. Check "
               "whether the expression is well-formed with the detection idiom (std::void_t or requires), print that "
               "result, and use the expression ONLY inside a function template that depends on the types involved, "
               "guarded by `if constexpr`. This matters: `if constexpr` in a plain function such as main() does NOT "
               "discard the other branch, so the old library would still fail to compile. Call that function template "
               "from main. When the expression is supported, exercise it fully (print every result, wrap throwing "
               "calls in try/catch). Keep the same types and inputs. Skeleton:\n"
               "```cpp\n"
               "template <class J, class K, class = void> struct can_use : std::false_type {};\n"
               "template <class J, class K>\n"
               "struct can_use<J, K, std::void_t<decltype(std::declval<J&>()[std::declval<K>()])>> : std::true_type {};\n"
               "template <class J, class K> void probe(J& j, K&& k) {\n"
               "    std::cout << \"supported: \" << can_use<J, K>::value << \"\\n\";\n"
               "    if constexpr (can_use<J, K>::value) { /* use j[k] here, print results */ }\n"
               "}\n"
               "```\n"
               "(Replace the decltype expression with the one under test.)"),
}


def die(msg):
    sys.exit(f"fix.py: {msg}")


HEADER = re.compile(r"\A(?://\s*(?:generated by|intent:)[^\n]*\n)+")


def strip_header(code):
    """Drop the two `// generated by ...` / `// intent: ...` comment lines write_tests puts on top of each program."""
    return HEADER.sub("", code)


def errors_of(stderr, limit=1200):
    """The `error:` lines of a compiler log (first few, clipped, directories removed so no host paths leave the machine);
    older results.json hold raw tails, so filter here too."""
    text = re.sub(r"(?:[A-Za-z]:)?[\w.+/\\-]*[/\\]", "", stderr or "")
    lines = [l.strip()[:300] for l in text.splitlines() if "error" in l.lower()][:6]
    return generate.clip("\n".join(lines) or text, limit)


def pick(manifest, results, limit, per_signature=4):
    """Entries worth repairing -> [{"file", "kind", "name", "intent", "errors"}] (see module docstring for the rules).
    At most `per_signature` detect candidates share one first-compiler-error kind: when a dozen programs fail on old for
    the same reason, repairing a few of them shows the same new behavior and the rest only add near-duplicates."""
    out, seen = [], {}
    for e in manifest["tests"]:
        r = results.get(e["file"])
        if e.get("superseded_by") or not r:
            continue
        old, new = r["old"], r["new"]
        if r["status"] == "invalid" and not old["compile_ok"] and not new["compile_ok"]:
            out.append({**e, "kind": "compile", "errors": errors_of(old["compile_stderr"])})
        elif r["status"] == "compile_diff" and r["compile_failed_on"] == "old":
            sig = run.error_signature(old["compile_stderr"])
            seen[sig] = seen.get(sig, 0) + 1
            if seen[sig] <= per_signature:
                out.append({**e, "kind": "detect", "errors": errors_of(old["compile_stderr"], 800)})
    return out[:limit]


def build_prompt(t, rec, gh, tests_dir, items):
    section, _ = generate.pr_section(t, rec, gh)
    parts = [section, "", "# Programs to repair", ""]
    for it in items:
        src = (Path(tests_dir) / it["file"]).read_text(encoding="utf-8")
        parts += [f"## {it['file']} ({it['kind']})", f"Intent: {it['intent']}", KIND_TEXT[it["kind"]],
                  "Compiler errors:", "```", it["errors"], "```", "Source:", "```cpp", generate.clip(strip_header(src), 5000), "```", ""]
    parts += ["# Task", "Return JSON with a \"fixes\" array: one item per program above, with \"file\" (exactly as given) "
              "and \"code\" (the complete repaired program, standalone, with its own int main). Do not return programs "
              "you cannot repair."]
    return generate.system_prompt(t), "\n".join(parts)


def parse_fixes(text, wanted):
    """-> {file: code} for files in `wanted` whose repaired code has a main(); anything else is ignored."""
    try:
        items = json.loads(text)["fixes"]
    except (ValueError, KeyError, TypeError):
        die(f"model did not return the expected JSON: {text[:300]!r}")
    out = {}
    for it in items:
        f = (it.get("file") or "").strip()
        code = strip_header(generate.unflatten(re.sub(r"^```[a-z+]*\n|\n```\s*$", "", (it.get("code") or "").strip())).strip() + "\n")
        if f in wanted and f not in out and re.search(r"\bint\s+main\s*\(", code):
            out[f] = code
    return out


def evaluate(env, tests_dir, names, args):
    """Compile and run `names` on both versions (run.py's workers) -> {name: result entry as in results.json}."""
    with ThreadPoolExecutor(2) as ex:
        fo, fn = (ex.submit(run.run_batch, env, w, tests_dir, names, args) for w in ("old", "new"))
        old, new = fo.result(), fn.result()
    out = {}
    for n in names:
        status, failed_on = run.classify(old[n], new[n])
        out[n] = {"status": status, "compile_failed_on": failed_on, "old": old[n], "new": new[n]}
    return out


def merge_results(tests_dir, new_entries):
    path = Path(tests_dir) / "results.json"
    doc = json.loads(path.read_text())
    doc["tests"].update(new_entries)
    doc["tests"] = dict(sorted(doc["tests"].items()))
    counts = {}
    for v in doc["tests"].values():
        counts[v["status"]] = counts.get(v["status"], 0) + 1
    doc["summary"] = counts
    write_text(path, json.dumps(doc, indent=2) + "\n")


def fix_round(t, rec, gh, env, tests_dir, manifest, results, args, round_no):
    items = pick(manifest, results, args.max_per_round, args.per_signature)
    if not items:
        print(f"round {round_no}: nothing to repair")
        return None
    by_kind = {k: sum(1 for i in items if i["kind"] == k) for k in KIND_TEXT}
    print(f"round {round_no}: {len(items)} candidates ({by_kind['compile']} compile, {by_kind['detect']} detect)")
    system, prompt = build_prompt(t, rec, gh, tests_dir, items)
    write_text(Path(tests_dir) / f"fix.round{round_no}.prompt.txt", f"[system]\n{system}\n\n[user]\n{prompt}\n")
    if args.dry_run:
        for i in items:
            print(f"  {i['kind']:<8}{i['file']}")
        print(f"dry run: prompt ({len(system) + len(prompt)} chars) written to {tests_dir}/fix.round{round_no}.prompt.txt")
        return None
    r = llm.call(prompt, system=system, schema=SCHEMA, model=args.model, force=args.force)
    fixed = parse_fixes(r["text"], {i["file"] for i in items})
    if not fixed:
        print(f"round {round_no}: the model returned no usable repair")
        return None
    start = 1 + max(int(re.search(r"\d+", e["file"]).group()) for e in manifest["tests"])
    progs = [{"name": f"{it['name']}_fixed", "intent": it["intent"], "code": fixed[it["file"]]}
             for it in items if it["file"] in fixed]
    entries = generate.write_tests(Path(tests_dir), progs, start, r["model"], rec["pr"], round_no)
    new_items = [it for it in items if it["file"] in fixed]
    for e, it in zip(entries, new_items):
        e["fixes"], e["kind"] = it["file"], it["kind"]
        next(x for x in manifest["tests"] if x["file"] == it["file"])["superseded_by"] = e["file"]
    manifest["tests"] += entries
    generate.save_manifest(Path(tests_dir), manifest)
    print(f"round {round_no}: {len(entries)} repairs written ({'cache' if r['cached'] else 'API'}; "
          f"{llm.calls_today(r['model'])}/{llm.limits(r['model'])[1]} requests used today); running them ...")
    res = evaluate(env, Path(tests_dir), [e["file"] for e in entries], args)
    merge_results(tests_dir, res)
    results.update(res)
    for e, it in zip(entries, new_items):
        x = res[e["file"]]
        extra = f" (fails on {x['compile_failed_on']})" if x["compile_failed_on"] else ""
        print(f"  {it['kind']:<8}{it['file']} -> {e['file']}: {results[it['file']]['status']} -> {x['status']}{extra}")
    return entries


def fix(t, pr, args, tests_dir=None, env=None):
    tests_dir = Path(tests_dir or t.data / "tests" / str(pr))
    for need in ("generated.json", "results.json"):
        if not (tests_dir / need).is_file():
            die(f"{tests_dir / need} is missing; run generate.py and run.py first")
    manifest = json.loads((tests_dir / "generated.json").read_text())
    results = json.loads((tests_dir / "results.json").read_text())["tests"]
    rec, gh = generate.load_pr(t, pr)
    if env is None and not args.dry_run:
        from env import prepare
        env = prepare(t.name, pr, docker=args.docker)
    base = max((e["round"] for e in manifest["tests"]), default=0)
    for round_no in range(base + 1, base + args.rounds + 1):
        if fix_round(t, rec, gh, env, tests_dir, manifest, results, args, round_no) is None:
            break
    if not args.dry_run:  # lets batch.py (and you) tell "ran, nothing left" from "never ran"
        manifest["fix"] = {"rounds_max": args.rounds, "model": args.model}
        generate.save_manifest(tests_dir, manifest)
    live = {}
    for e in manifest["tests"]:
        if not e.get("superseded_by") and e["file"] in results:
            live[results[e["file"]]["status"]] = live.get(results[e["file"]]["status"], 0) + 1
    print(f"programs in use (superseded ones excluded): {live}")
    return manifest


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("target")
    ap.add_argument("--pr", type=int, required=True)
    ap.add_argument("--rounds", type=int, default=2, help="at most this many repair rounds (one request each)")
    ap.add_argument("--max-per-round", type=int, default=15)
    ap.add_argument("--per-signature", type=int, default=4,
                    help="at most this many detect repairs per kind of old-side compile error")
    ap.add_argument("--model", default=llm.DEFAULT_MODEL)
    ap.add_argument("--dry-run", action="store_true", help="list candidates and save the prompt, make no request")
    ap.add_argument("--force", action="store_true", help="ignore the response cache (costs a request)")
    ap.add_argument("--docker", action="store_true")
    ap.add_argument("--std", default="c++17")
    ap.add_argument("--runs", type=int, default=3)
    ap.add_argument("--timeout", type=float, default=10)
    ap.add_argument("--compile-timeout", type=float, default=180)
    ap.add_argument("--jobs", type=int, default=4)
    args = ap.parse_args()
    try:
        fix(Target(args.target), args.pr, args)
    except llm.QuotaExhausted as e:
        print(f"fix.py: {e}", file=sys.stderr)
        sys.exit(3)


if __name__ == "__main__":
    main()
