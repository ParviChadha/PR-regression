#!/usr/bin/env python3
"""Classification (pipeline stage "Classify"): is each behavioral difference the PR intended?

Usage:  python3 pipeline/classify.py <target> --pr N [--model M] [--dry-run] [--force]
Run generate.py, run.py (and fix.py) first. Needs GEMINI_API_KEY (in .env or exported) unless the response is cached.

1. Collect the programs in use (generated.json entries that are not superseded) whose result is a difference:
   output_diff, or compile_diff (fails on old = new capability; fails on new = something that worked now breaks;
   fails on both with different errors). same / invalid / flaky programs carry no difference and are only counted.
2. Cluster them by what they show: status + the first differing output line pair (or the first compiler error kind).
   Ten programs that all show "supported: 0 -> supported: 1" become ONE cluster with a count and two representatives.
3. ONE request per PR: the merge-time PR text and diff plus every cluster (representative sources, old/new outputs or
   compiler errors). The model returns, per cluster, intended | unintended | unclear, a confidence and a reason.
   Only information available at merge time is used (same leak filter as generate.py): a later report of the
   regression would give the answer away.
4. Writes data/<t>/tests/<pr>/classification.json (clusters with verdicts, and pr_verdict.regression_candidate = at least
   one cluster judged unintended) and classify.prompt.txt (the exact prompt, for audit).

Verdicts: intended = the PR text (title, description, linked issue, pre-merge discussion, diff) states or clearly implies
this change; unintended = it contradicts the PR's goal, breaks a contract that held before, or is a side effect the PR
never mentions (including a feature the PR claims but only partly delivers); unclear = cannot tell, or the test itself
looks unreliable (undefined behavior, environment dependence).
"""
import argparse
import hashlib
import json
import sys
from itertools import zip_longest
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT))
from pipeline.common import Target, write_text  # noqa: E402
import fix  # noqa: E402
import generate  # noqa: E402
import llm  # noqa: E402
import run  # noqa: E402

VERDICTS = ("intended", "unintended", "unclear")
MAX_CLUSTERS = 12
REPRESENTATIVES = 2

SYSTEM = """You review the results of differential testing for ONE pull request to a C++ library. Test programs were
compiled and run against the library before the PR and after it; the clusters below are the programs whose behavior
differs. For each cluster decide whether the difference is something the PR intended.

Use only the PR text and diff given here. Verdicts:
- intended: the title, description, linked issue, discussion before merge or the diff states or clearly implies this change.
- unintended: the difference contradicts the PR's stated goal, breaks something that worked or was documented before, or is
  a side effect the PR never mentions. A new capability the PR adds that is only partly delivered also counts: if the PR
  makes an input type accepted, but a closely related use of that same type fails to compile or misbehaves after the PR,
  the failing use is unintended.
- unclear: you cannot tell from the PR text, or the program itself looks unreliable (undefined behavior, uninitialized
  data, environment dependence, depends on an internal detail).

Reading the evidence: a program that fails to compile on the old version and works on the new one shows a new capability.
One that compiled before and fails to compile now means previously valid code broke. A cluster with a different compiler
error on each side means the failure mode changed (for example a clean "no matching function" became a hard error
inside the library); judge what that means for users. Test programs are generated by a model and can be wrong; do not
treat a program's own comments or intent as evidence of what the library should do.

Be concise and specific: the reason is one or two sentences that name the behavior and the PR text or diff line it
rests on. Give a verdict for every cluster id."""

SCHEMA = {"type": "OBJECT", "properties": {"clusters": {"type": "ARRAY", "items": {
    "type": "OBJECT",
    "properties": {"id": {"type": "STRING"}, "verdict": {"type": "STRING"}, "confidence": {"type": "STRING"},
                   "reason": {"type": "STRING"}},
    "required": ["id", "verdict", "confidence", "reason"]}}}, "required": ["clusters"]}


def die(msg):
    sys.exit(f"classify.py: {msg}")


# ---------------------------------------------------------------- clustering
def stdout_of(side):
    return (side["runs"][0].get("stdout") or "") if side.get("runs") else ""


def first_diff(old, new):
    """First differing line of the two outputs as (old line, new line), clipped; exit-code/timeout change if the text is equal."""
    o, n = stdout_of(old), stdout_of(new)
    if o == n:
        ro, rn = old["runs"][0], new["runs"][0]
        return (f"exit {ro['exit']}{' (timeout)' if ro['timeout'] else ''}", f"exit {rn['exit']}{' (timeout)' if rn['timeout'] else ''}")
    for a, b in zip_longest(o.splitlines(), n.splitlines(), fillvalue=""):
        if a != b:
            return a.strip()[:80], b.strip()[:80]
    return o[:80], n[:80]


def signature(r):
    if r["status"] == "output_diff":
        return ("output_diff", None, first_diff(r["old"], r["new"]))
    failed = r["compile_failed_on"]
    sigs = tuple(run.error_signature(r[w]["compile_stderr"]) for w in (("old", "new") if failed == "both" else (failed,)))
    return ("compile_diff", failed, sigs)


def collect(manifest, results):
    """-> (clusters, counts). Cluster = {"id", "key", "status", "failed_on", "programs": [file, ...]}, biggest first."""
    groups, counts = {}, {"same": 0, "invalid": 0, "flaky": 0, "superseded": 0, "missing": 0}
    for e in manifest["tests"]:
        r = results.get(e["file"])
        if e.get("superseded_by"):
            counts["superseded"] += 1
        elif r is None:
            counts["missing"] += 1
        elif r["status"] in ("output_diff", "compile_diff"):
            groups.setdefault(json.dumps(signature(r)), []).append(e["file"])
        else:
            counts[r["status"]] = counts.get(r["status"], 0) + 1
    ordered = sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[1][0]))
    clusters = []
    for i, (key, files) in enumerate(ordered, 1):
        sig = json.loads(key)
        clusters.append({"id": f"C{i}", "status": sig[0], "failed_on": sig[1], "programs": files})
    return clusters, counts


# ---------------------------------------------------------------- prompt
def describe(cluster, results, tests_dir):
    r0 = results[cluster["programs"][0]]
    n = len(cluster["programs"])
    head = f"## {cluster['id']}: {cluster['status']}" + (f" (fails to compile on {cluster['failed_on']})" if cluster["failed_on"] else "")
    out = [f"{head}, {n} program{'s' if n != 1 else ''}: {', '.join(cluster['programs'])}"]
    if cluster["status"] == "output_diff":
        a, b = first_diff(r0["old"], r0["new"])
        out.append(f"First difference (old -> new): `{a}` -> `{b}`")
    for f in cluster["programs"][:REPRESENTATIVES]:
        r = results[f]
        src = generate.clip(fix.strip_header((Path(tests_dir) / f).read_text(encoding="utf-8")), 3000)
        out += ["", f"### {f}", "```cpp", src, "```"]
        for w in ("old", "new"):
            s = r[w]
            if s["compile_ok"]:
                out += [f"Output on {w} (exit {s['runs'][0]['exit']}):", "```", generate.clip(stdout_of(s), 600), "```"]
            else:
                out += [f"Compiler errors on {w}:", "```", fix.errors_of(s["compile_stderr"], 700), "```"]
    return "\n".join(out)


def build_prompt(t, rec, gh, tests_dir, clusters, counts, results):
    section, _ = generate.pr_section(t, rec, gh)
    total = sum(len(c["programs"]) for c in clusters) + counts["same"] + counts["invalid"] + counts["flaky"]
    parts = [section, "", "# Differential test results",
             f"{total} programs were compiled and run on both versions. {counts['same']} behaved identically, "
             f"{counts['invalid']} were unusable (fail the same way on both), {counts['flaky']} were nondeterministic. "
             f"{sum(len(c['programs']) for c in clusters)} differ, in {len(clusters)} cluster{'s' if len(clusters) != 1 else ''}:", ""]
    shown = clusters[:MAX_CLUSTERS]
    parts += [describe(c, results, tests_dir) + "\n" for c in shown]
    if len(clusters) > len(shown):
        parts.append(f"({len(clusters) - len(shown)} smaller clusters are not shown.)\n")
    parts += ["# Task", "Return JSON with a \"clusters\" array: for every cluster id above give \"id\", \"verdict\" "
              "(intended, unintended or unclear), \"confidence\" (high, medium or low) and \"reason\"."]
    return SYSTEM, "\n".join(parts), shown


def parse_verdicts(text, shown):
    """-> {id: {"verdict", "confidence", "reason"}} for every shown cluster; a missing or unrecognized verdict becomes unclear."""
    try:
        items = json.loads(text)["clusters"]
    except (ValueError, KeyError, TypeError):
        die(f"model did not return the expected JSON: {text[:300]!r}")
    got = {}
    for it in items:
        cid, v = str(it.get("id", "")).strip(), str(it.get("verdict", "")).strip().lower()
        if cid and cid not in got:
            got[cid] = {"verdict": v if v in VERDICTS else "unclear",
                        "confidence": str(it.get("confidence", "")).strip().lower() or "low",
                        "reason": " ".join(str(it.get("reason", "")).split())}
            if v not in VERDICTS:
                got[cid]["reason"] = f"[model gave verdict {v!r}] " + got[cid]["reason"]
    for c in shown:
        got.setdefault(c["id"], {"verdict": "unclear", "confidence": "low", "reason": "[the model gave no verdict for this cluster]"})
    return got


# ---------------------------------------------------------------- run
def classify(t, pr, args, tests_dir=None):
    tests_dir = Path(tests_dir or t.data / "tests" / str(pr))
    for need in ("generated.json", "results.json"):
        if not (tests_dir / need).is_file():
            die(f"{tests_dir / need} is missing; run generate.py and run.py first")
    manifest = json.loads((tests_dir / "generated.json").read_text())
    results = json.loads((tests_dir / "results.json").read_text())["tests"]
    rec, gh = generate.load_pr(t, pr)
    clusters, counts = collect(manifest, results)
    print(f"PR #{pr}: {sum(len(c['programs']) for c in clusters)} differing programs in {len(clusters)} clusters; "
          f"same={counts['same']} invalid={counts['invalid']} flaky={counts['flaky']} superseded={counts['superseded']}")
    for c in clusters:
        print(f"  {c['id']:<4}{c['status']:<13}{('[' + c['failed_on'] + ']') if c['failed_on'] else '':<7}{len(c['programs']):>3} programs  {c['programs'][0]}")
    if not clusters:
        print("nothing differs: no regression candidate")
        doc = {"target": t.name, "pr": pr, "model": None, "clusters": [], "counts": counts,
               "results_sha256": hashlib.sha256((tests_dir / "results.json").read_bytes()).hexdigest(),
               "pr_verdict": {"regression_candidate": False, "unintended_clusters": []}}
        write_text(tests_dir / "classification.json", json.dumps(doc, indent=2) + "\n")
        return doc
    system, prompt, shown = build_prompt(t, rec, gh, tests_dir, clusters, counts, results)
    write_text(tests_dir / "classify.prompt.txt", f"[system]\n{system}\n\n[user]\n{prompt}\n")
    if args.dry_run:
        print(f"dry run: prompt ({len(system) + len(prompt)} chars) written to {tests_dir / 'classify.prompt.txt'}")
        return None
    r = llm.call(prompt, system=system, schema=SCHEMA, model=args.model, temperature=0.0, force=args.force)
    verdicts = parse_verdicts(r["text"], shown)
    out = []
    for c in shown:
        out.append({**c, **verdicts[c["id"]]})
    bad = [c["id"] for c in out if c["verdict"] == "unintended"]
    doc = {"target": t.name, "pr": pr, "model": r["model"], "prompt_sha256": hashlib.sha256((system + prompt).encode()).hexdigest(),
           "results_sha256": hashlib.sha256((tests_dir / "results.json").read_bytes()).hexdigest(),
           "clusters": out, "clusters_not_shown": len(clusters) - len(shown), "counts": counts,
           "pr_verdict": {"regression_candidate": bool(bad), "unintended_clusters": bad}, "usage": r.get("usage")}
    write_text(tests_dir / "classification.json", json.dumps(doc, indent=2) + "\n")
    print(f"({'cache' if r['cached'] else 'API'}; {llm.calls_today(r['model'])}/{llm.limits(r['model'])[1]} requests used today)")
    for c in out:
        print(f"  {c['id']:<4}{c['verdict']:<11}{c['confidence']:<7}{c['reason']}")
    print(f"regression candidate: {doc['pr_verdict']['regression_candidate']} {bad or ''}\nwrote {tests_dir / 'classification.json'}")
    return doc


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("target")
    ap.add_argument("--pr", type=int, required=True)
    ap.add_argument("--model", default=llm.DEFAULT_MODEL)
    ap.add_argument("--dry-run", action="store_true", help="show the clusters and save the prompt, make no request")
    ap.add_argument("--force", action="store_true", help="ignore the response cache (costs a request)")
    args = ap.parse_args()
    try:
        classify(Target(args.target), args.pr, args)
    except llm.QuotaExhausted as e:
        print(f"classify.py: {e}", file=sys.stderr)
        sys.exit(3)


if __name__ == "__main__":
    main()
